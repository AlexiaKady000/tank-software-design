/**
 * Архитектурная карта текущего проекта.
 *
 * <p>Метки {@code Type} и {@code role} описывают ответственность
 * типа, а не доказывают соблюдение архитектуры расположением файла в пакете.
 * Входной порт вызывается внешним участником, выходной порт вызывается ядром.
 * Адаптер связывает такой контракт с конкретной средой. Внутренний интерфейс
 * модели или Strategy сам по себе не является портом.</p>
 *
 * <p><b>Domain:</b> Tank, Bullet и Tree являются сущностями; Field владеет
 * runtime-агрегатом мира; Direction представляет значение; TankState и
 * HealthTankState задают поведение; CollisionSystem и GameCollisions содержат
 * доменные правила; Level описывает начальный уровень, а RandomTankGenerator
 * реализует доменную фабрику. Не все типы этого слоя являются entities.</p>
 *
 * <p><b>Application:</b> команды MoveCommand и ShootCommand выполняют сценарии,
 * InputController и TankInputHandler координируют получение действий,
 * RandomControlStrategy реализует AI-политику, RandomLevelLoader предоставляет
 * внутрипроцессную реализацию загрузки. ToggleHealthBarsCommand относится
 * к сценарию представления, а не к физике игрового мира.</p>
 *
 * <p><b>Infrastructure:</b> FileLevelLoader адаптирует файловую систему,
 * KeyboardControlStrategy обслуживает опрашиваемый порт ввода, WorldGraphics и его
 * графические компоненты адаптируют модель к libGDX. GraphicsFactory,
 * HealthBarVisibility и util являются вспомогательными типами этого слоя.
 * GameDesktopLauncher является composition root и адаптером жизненного цикла,
 * но сейчас также содержит application-координацию запуска и кадра.</p>
 *
 * <p><b>Существующие порты:</b> Command задает минимальный входной контракт
 * выполнения действий; LevelLoader является выходным портом получения уровня;
 * ControlStrategy является выходным портом запроса управляющего решения;
 * LevelObserver является выходным портом событий состава мира. ObservableLevel
 * обслуживает подписку. IntPredicate, BooleanSupplier и Runnable выполняют
 * роль функциональных границ там, где связываются ввод и представление;
 * отдельный именованный интерфейс не обязателен для каждой такой функции.</p>
 *
 * <p><b>Недостающие границы и возможные улучшения:</b></p>
 * <ol>
 *   <li>Общего входного порта игровой сессии и application-сервиса, который
 *   выполняет запуск, команды и шаг времени без libGDX. Эти действия пока
 *   распределены между командами и GameDesktopLauncher. Их следует собрать
 *   в GameSession с входным GameUseCases; названия здесь являются предложением,
 *   эти типы пока не реализованы.</li>
 *   <li>Независимого от libGDX языка модели: GridPoint2 и MathUtils
 *   связывают ядро с библиотекой движка. Для строгой изоляции
 *   координаты и математические операции должны принадлежать ядру, а перевод
 *   в типы libGDX выполняться на стороне графических адаптеров.</li>
 *   <li>Четкого размещения существующих границ: чтение Gdx.input и создание
 *   команд L сейчас находятся в launcher-лямбдах. Это уже функциональные
 *   адаптеры; их можно выделить в отдельный KeyboardInputAdapter для ясности,
 *   но новые интерфейсы ради самого наличия интерфейсов не нужны.</li>
 *   <li>Более предметного контракта ошибки LevelLoader: вместо IOException
 *   можно определить ошибку загрузки сценария в application и преобразовывать
 *   технические исключения внутри FileLevelLoader. Это улучшение семантики
 *   существующего порта, а не отсутствие порта или самостоятельное нарушение DIP.</li>
 * </ol>
 *
 * <p>Направление порта определяется вызовом, а не направлением данных:
 * TankInputHandler вызывает ControlStrategy, поэтому клавиатурная реализация
 * обслуживает выходной запрос ядра, хотя данные клавиш поступают в игру.
 * GameDesktopLauncher, вызываемый libGDX, является входным адаптером.</p>
 *
 * <p>Отдельный выходной порт отрисовки нужен только если application сам
 * запрашивает кадр. При внешнем цикле libGDX и существующем LevelObserver
 * его отсутствие не является автоматическим нарушением архитектуры.
 * WorldContext, MovementField, Health, TankState и CollisionHandler являются
 * внутренними контрактами ядра. Renderable и ObjectGraphics являются SPI
 * инфраструктуры с типами libGDX, а не независимыми портами ядра.</p>
 *
 * <p>Тестовые классы и вспомогательные doubles отмечены как test и не
 * классифицируются как production entities, use cases или adapters.
 * Разметка документирует текущий код; слои и поведение этой правкой
 * не перераспределяются.</p>
 */
